"""Run retrieval evals: recall@3 and MRR over eval_set.json.

Metrics (per question, k=3):
- recall@3 = (# relevant docs appearing in top-3) / (# relevant docs)
- reciprocal rank = 1 / rank of the first retrieved chunk from a relevant doc
  (0 if none in top-3)

Aggregates are plain means. Results are written to evals/results.json —
the numbers in the README come from this file, generated by this script.
"""

from __future__ import annotations

import json
import sys
from datetime import datetime, timezone
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent.parent / "rag"))

from embed import Index
from retrieve import search

K = 3
EVAL_DIR = Path(__file__).parent


def evaluate(index: Index, eval_set: list[dict]) -> dict:
    per_question = []
    for item in eval_set:
        relevant = set(item["relevant_docs"])
        retrieved = [chunk.doc for chunk, _ in search(item["question"], index, k=K)]

        hits = len(set(retrieved) & relevant)
        recall = hits / len(relevant)

        rr = 0.0
        for rank, doc in enumerate(retrieved, start=1):
            if doc in relevant:
                rr = 1.0 / rank
                break

        per_question.append(
            {
                "question": item["question"],
                "relevant_docs": sorted(relevant),
                "retrieved_docs": retrieved,
                "recall@3": round(recall, 3),
                "reciprocal_rank": round(rr, 3),
            }
        )

    return {
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "backend": index.backend,
        "k": K,
        "n_questions": len(eval_set),
        "recall@3": round(sum(q["recall@3"] for q in per_question) / len(per_question), 3),
        "mrr": round(sum(q["reciprocal_rank"] for q in per_question) / len(per_question), 3),
        "questions": per_question,
    }


def main() -> None:
    eval_set = json.loads((EVAL_DIR / "eval_set.json").read_text())
    results = evaluate(Index.load(), eval_set)
    out = EVAL_DIR / "results.json"
    out.write_text(json.dumps(results, indent=2))
    print(f"backend={results['backend']}  n={results['n_questions']}")
    print(f"recall@3 = {results['recall@3']}")
    print(f"mrr      = {results['mrr']}")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
